#!/usr/bin/env python3
"""Adds the EMR and sync-gateway secrets to .env, generating each one only if it is missing. Prints names, never values."""
import base64
import os
import secrets
import subprocess

PATH = os.path.join(os.path.dirname(__file__), "..", "..", ".env")


def rsa_key_b64():
    pem = subprocess.run(["openssl", "genrsa", "2048"], capture_output=True, check=True).stdout
    return base64.b64encode(pem).decode()


GENERATORS = {
    "OPENMRS_DB_PASSWORD": lambda: secrets.token_hex(16),
    "OPENMRS_DB_ROOT_PASSWORD": lambda: secrets.token_hex(16),
    # The reference application's built-in administrator; the sync gateway uses its own account
    "OPENMRS_ADMIN_PASSWORD": lambda: "Admin123",
    "OPENMRS_SYNC_PASSWORD": lambda: "Sync" + secrets.token_hex(8) + "A1",
    "OPENFN_DB_PASSWORD": lambda: secrets.token_hex(16),
    "OPENFN_SECRET_KEY_BASE": lambda: base64.b64encode(secrets.token_bytes(64)).decode(),
    "OPENFN_ENCRYPTION_KEY": lambda: base64.b64encode(secrets.token_bytes(32)).decode(),
    "OPENFN_WORKER_SECRET": lambda: secrets.token_hex(32),
    "OPENFN_WORKER_RUNS_PRIVATE_KEY": rsa_key_b64,
    "OPENFN_ADMIN_PASSWORD": lambda: "Lightning-" + secrets.token_hex(6),
    "EBUZIMA_DB_ROOT_PASSWORD": lambda: secrets.token_hex(16),
    "EBUZIMA_ADMIN_PASSWORD": lambda: "Ebuzima-" + secrets.token_hex(6),
    "EBUZIMA_API_KEY": lambda: secrets.token_hex(8),
    "EBUZIMA_API_SECRET": lambda: secrets.token_hex(16),
    "EBUZIMA_NURSE_PASSWORD": lambda: "Nurse-" + secrets.token_hex(6),
    # Shared between the core's internal sync endpoints and the gateway's credential
    "SYNC_KEY": lambda: secrets.token_hex(24),
}

lines = open(PATH).read().splitlines() if os.path.exists(PATH) else []
present = {l.split("=", 1)[0] for l in lines if "=" in l and not l.startswith("#")}
added = []
for name, make in GENERATORS.items():
    if name not in present:
        lines.append(f"{name}={make()}")
        added.append(name)
if added:
    if "# EMR and sync gateway (generated by scripts/emr/env.py)" not in lines:
        lines.insert(len(lines) - len(added), "# EMR and sync gateway (generated by scripts/emr/env.py)")
    open(PATH, "w").write("\n".join(lines) + "\n")
print("generated:", ", ".join(added) if added else "nothing (all present)")
